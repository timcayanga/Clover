import assert from 'node:assert/strict';
import { OnboardingPersistence } from '../src/onboarding-persistence.ts';
const rows = new Map();
const store = { get: async k => rows.get(k) ?? null, set: async (k,v) => rows.set(k,v), remove: async k => rows.delete(k) };
const choices = { experience: 'beginner', currency:'PHP', locale:'en-PH', timeZone:'Asia/Manila' };
let calls=0, finish;
const send = () => { calls++; return new Promise(resolve => { finish=resolve; }); };
const queue = new OnboardingPersistence(store, send);
await queue.init(); await queue.save(choices);
assert.equal(calls,0,'Local completion does not wait for the server');
assert.deepEqual(rows.get('pending-onboarding'), choices);
const first=queue.flush(), duplicate=queue.flush();assert.equal(first,duplicate);assert.equal(calls,1);
assert.deepEqual(queue.pending,choices,'In-flight work survives navigation');
finish(); await first;assert.equal(queue.pending,null);assert.equal(rows.size,0);assert.equal(queue.completed,true);
await queue.save(choices);
const failed = new OnboardingPersistence(store, async()=>{throw new Error('Offline');});await failed.init();
await assert.rejects(failed.flush(), /Offline/);assert.deepEqual(rows.get('pending-onboarding'),choices);
const restarted = new OnboardingPersistence(store,async()=>({completed:true}));await restarted.init();assert.deepEqual(restarted.pending,choices);await restarted.flush();assert.equal(rows.size,0);
const isolated = new OnboardingPersistence({ ...store, get:async()=>null },send);await isolated.init();assert.equal(isolated.pending,null);
console.log('PASS onboarding persistence: nonblocking local completion, single flight, failed request retention, restart retry and identity isolation');
