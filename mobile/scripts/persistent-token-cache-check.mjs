import assert from 'node:assert/strict';
import {createPersistentTokenCache} from '../src/persistent-token-cache.ts';
const values = new Map();let failRead=false,failWrite=false,deletions=0;
const storage={get:async k=>{if(failRead)throw Error('Keychain temporarily locked');return values.get(k)??null;},set:async(k,v)=>{if(failWrite)throw Error('Disk unavailable');values.set(k,v);},remove:async k=>{deletions++;values.delete(k);}};
let process=createPersistentTokenCache(storage);
await process.cache.saveToken('existing-clerk-key','encrypted-fixture');
process=createPersistentTokenCache(storage);
assert.equal(await process.cache.getToken('existing-clerk-key'),'encrypted-fixture','Cold process restores existing native credentials');
failRead=true;
await assert.rejects(process.cache.getToken('existing-clerk-key'),/temporarily locked/);
assert.equal(deletions,0,'Temporary storage errors never delete the session');
assert.equal(values.get('existing-clerk-key'),'encrypted-fixture');
failRead=false;
assert.equal(await process.cache.getToken('existing-clerk-key'),'encrypted-fixture');
await process.setRememberSession(false);
assert.equal(values.has('existing-clerk-key'),false,'Explicit remember-off clears credentials already read from disk');
await process.cache.saveToken('existing-clerk-key','memory-fixture');
assert.equal(await process.cache.getToken('existing-clerk-key'),'memory-fixture');
assert.equal(await createPersistentTokenCache(storage).cache.getToken('existing-clerk-key'),null,'Remember-off remains process-local');
await process.setRememberSession(true);
assert.equal(await createPersistentTokenCache(storage).cache.getToken('existing-clerk-key'),'memory-fixture','Re-enabling persistence saves current credentials');
await Promise.all([process.cache.saveToken('existing-clerk-key','rotated'),process.cache.clearToken('existing-clerk-key')]);
assert.equal(await createPersistentTokenCache(storage).cache.getToken('existing-clerk-key'),null,'Sign-out wins over an earlier queued rotation');
failRead=true;
await assert.rejects(createPersistentTokenCache(storage).cache.getToken('key'),/temporarily locked/);
failRead=false;failWrite=true;
await assert.rejects(process.cache.saveToken('write-key','fixture'),/unavailable/);
failWrite=false;
await process.cache.saveToken('write-key','recovered');
assert.equal(await process.cache.getToken('write-key'),'recovered','A failed operation cannot poison the queue');
console.log('PASS persistent native sessions: cold restarts, legacy keys, transient keychain failures, explicit sign-out, preference changes and write ordering');
