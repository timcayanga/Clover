import { createHash, randomUUID } from "node:crypto";
import { Prisma } from "@prisma/client";
import { prisma } from "./prisma";
import { agentProfiles, studioSchema } from "./team-studio";
import { emptyServerStudio } from "./team-studio-server-state";
import { teamReportSchema, type TeamReport } from "./team-report-contract";

// Authenticated API and trusted coordinator CLI share this idempotent import.
// No automatic approval: owner must review imported reports like generated work.
export async function saveTeamReport(ownerId: string, raw: TeamReport) {
  const input = teamReportSchema.parse(raw);
  const hash = createHash("sha256").update(JSON.stringify(input)).digest("hex");
  const triggerKey = `report:${input.agent}:${input.reportKey}`;
  return prisma.$transaction(async (tx) => {
    await tx.$queryRaw`SELECT pg_advisory_xact_lock(hashtextextended(${ownerId}, 731))::text`;
    const old = await tx.teamAgentRun.findUnique({where: {ownerId_triggerKey: {ownerId, triggerKey}}});
    if (old) {
      if ((old.prompt as {reportHash?: string}).reportHash !== hash) throw new Error("CONFLICT");
      return {id: old.id, href: `/team/assignments/${old.id}`, duplicate: true, contentHash: hash};
    }
    const record = await tx.teamStudioState.findUnique({where: {ownerId}});
    const state = record ? studioSchema.parse(record.payload) : emptyServerStudio();
    if (state.briefs.length >= 200) throw new Error("STUDIO_CAPACITY");
    const id = randomUUID();
    const briefId = randomUUID();
    const role = agentProfiles.find(a => a.id === input.agent)!;
    const at = new Date();
    state.briefs.push({id: briefId, agent: input.agent, text: input.title, at: at.toISOString()});
    const revision = (record?.revision ?? 0) + 1;
    const payload = JSON.parse(JSON.stringify(state)) as Prisma.InputJsonValue;
    if (!record) await tx.teamStudioState.create({data: {ownerId, revision, payload}});
    else {
      const updated = await tx.teamStudioState.updateMany({where: {ownerId, revision: record.revision}, data: {revision, payload}});
      if (updated.count !== 1) throw new Error("CONFLICT");
    }
    await tx.teamStudioAudit.create({data: {ownerId, revision, payload}});
    await tx.teamAgentRun.create({data: {
      id, ownerId, briefId, agent: input.agent, triggerKey, model: "coordinator-report",
      status: "completed", reviewStatus: "pending", finishedAt: at,
      result: input.markdown, prompt: {brief: input.title, instructions: role.instructions, role: role.name, feedback: "", previousResult: "", reportHash: hash},
      events: {create: {action: "report_imported", note: `Saved coordinator report ${input.reportKey}. Pending owner review; not generated by a website model run.`}},
    }});
    return {id, href: `/team/assignments/${id}`, duplicate: false, contentHash: hash};
  });
}
