const transfer={merchantRaw:"Fund Transfer",merchantClean:"Fund Transfer",description:"Instapay to BPI ref 0123456789"};
const otherTransfer={...transfer,description:"Instapay to BPI ref 9876543210"};
assert.equal(bankTransactionMatches(transfer,otherTransfer),false,"Generic transfer names are not identity evidence");
assert.equal(bankTransactionMatches({...transfer,merchantClean:"Transfer to family"},{...otherTransfer,merchantClean:"Transfer to family"}),false,"Conflicting references outrank an identical display title");
assert.equal(bankTransactionsNeedReview(transfer,otherTransfer),false,"Different transfers with identical amounts are separate movements");
assert.equal(bankTransactionMatches(transfer,{...transfer}),true,"Specific identical source references retain one-to-one matching");
const base={id:"old",accountId:"a",date:"2026-10-01",amount:500,currency:"PHP",type:"expense",...transfer};
const overlap=createBankImportOverlapMatcher([base]);
assert.equal(overlap({...base,...otherTransfer}),"new");
assert.equal(overlap({...base,accountId:"b"}),"new","The receiving account is a separate side of a transfer");
assert.equal(overlap({...base,currency:"USD"}),"new","Different currencies are distinct movements");
assert.equal(overlap({...base,type:"income"}),"new","Opposite directions are not duplicate payments");
assert.equal(overlap(base),"matched");assert.equal(overlap(base),"new","An occurrence is consumed only once");
