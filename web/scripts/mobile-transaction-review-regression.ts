const refresh=pager.begin(1)!;
assert.equal(pager.current(second),false,"Refresh supersedes the older append");
pager.complete(second,2);
assert.equal(pager.busy,true,"A stale completion cannot release the refresh lock");
pager.complete(refresh,1);
const retry=pager.begin(2)!;assert(retry);
pager.complete(retry,2);assert.equal(pager.begin(2),null);
